#!/usr/bin/env bash
# Regenerate the Go and Rust targets from schema.py and refresh the receipt.
#
#   ./regen.sh            # regenerate
#   ./regen.sh check      # diff schema.py against the committed receipt, generate nothing
#
# The Dagr toolchain is not on PyPI; point DAGR_REPO at a checkout of it.
set -euo pipefail
cd "$(dirname "$0")"

DAGR_REPO="${DAGR_REPO:-$HOME/dev/RethinkingDagr}"
if [ ! -d "$DAGR_REPO/dagr" ]; then
  echo "regen: no Dagr checkout at $DAGR_REPO — set DAGR_REPO=/path/to/dagr" >&2
  exit 1
fi

cmd="${1:-build}"
PYTHONPATH="$DAGR_REPO" python3 -m dagr.cli "$cmd"

if [ "$cmd" = "build" ]; then
  # The shared-message conversions (AnyValue / KeyValue / Resource / Scope) are written
  # once, in pdatabridge/common.go against the traces package, and copied per signal:
  # each signal's generated package has its own flattened copy of OtlpCommon, so the Go
  # types differ and no generic unifies them (see the header of common.go).
  for sig in metric:metrics log:logs profile:profiles; do
    pkg="${sig%%:*}bridge"; gpkg="otlp${sig##*:}"
    mkdir -p "go/$pkg"
    { echo "// Code generated by regen.sh from pdatabridge/common.go; DO NOT EDIT."
      echo
      sed -e "s#^package pdatabridge\$#package $pkg#" \
          -e "s#\"otlpgen/otlptracesdirect\"#\"otlpgen/${gpkg}direct\"#" \
          -e "s#\"otlpgen/otlptraces\"#\"otlpgen/${gpkg}\"#" go/pdatabridge/common.go
    } > "go/$pkg/common_gen.go"
  done
  ( cd go && gofmt -l . | grep -v '^gen/' || true )
  ( cd go && go build ./... && go vet ./... )
  echo "regen: go build + vet clean"
  ( cd rust/gen && cargo build --release --quiet )
  echo "regen: rust (lazy + arrow) build clean"
fi
